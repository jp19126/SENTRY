"""Export actual raw parameter streams consumed by the whole-BERT host.

Offsets are bytes, tensors row-major little endian, no implicit alignment.
Every file is hashed. No hardware residency/capacity claim follows from size.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import sys
import numpy as np
import torch
sys.path.insert(0, str(Path(__file__).resolve().parent))
from model import LINEARS, load_model, inventory, sha

def float_keys():
    keys = ['bert.embeddings.'+s for s in ('word_embeddings.weight','position_embeddings.weight','token_type_embeddings.weight','LayerNorm.weight','LayerNorm.bias')]
    for i in range(4):
        p=f'bert.encoder.layer.{i}.'
        keys.extend(p+s for s in ('attention.self.query.bias','attention.self.key.bias','attention.self.value.bias','attention.output.dense.bias',
                                  'attention.output.LayerNorm.weight','attention.output.LayerNorm.bias','intermediate.dense.bias','output.dense.bias',
                                  'output.LayerNorm.weight','output.LayerNorm.bias'))
    keys += ['bert.pooler.dense.weight','bert.pooler.dense.bias','classifier.weight','classifier.bias']
    return keys

def export_model(model, out, metadata):
    out=Path(out); out.mkdir(parents=True, exist_ok=True)
    if model.variant=='fp32': raise ValueError('Export requires calibrated W8/A8 candidate; FP32 reference is separately retained')
    streams={'parameters_f32.bin':[(k,model.w(k).cpu().numpy().astype('<f4')) for k in float_keys()],
             'weights_i8.bin':[(n+'.weight',getattr(model,n.replace('.','__')+'__codes').cpu().numpy().astype('i1')) for n in LINEARS],
             'scales_f32.bin':[(n+'.weight_scale',getattr(model,n.replace('.','__')+'__scales').cpu().numpy().astype('<f4')) for n in LINEARS],
             'input_scales_f32.bin':[(n+'.input_scale',np.asarray([model.scales[n]],dtype='<f4')) for n in LINEARS]}
    manifest={'schema':'sentry_bert_aie_v1_raw_v1','model':metadata,'variant':model.variant,'byte_order':'little','layout':'C contiguous row major; weight [out,in]',
              'linear_order':list(LINEARS),'files':{},'tensors':[], 'source_inventory':inventory(model),
              'semantics':{'input_ids':'int32 [B,N], vocabulary30522','mask':'int32 [B,N], 1=valid key; bidirectional',
                           'token_type_ids':'int32 optional; default zero','positions':'0..N-1','N':256,
                           'quantization':'RNE signed[-127,127], zero_point0, per-output weight scalar/per-linear input scalar',
                           'bias':'(FP32(acc32)*input_scale)*weight_scale+bias in this order', 'attention':'BF16 operands/FP32 accumulation in K64 chunks' if 'bf16' in model.variant else 'FP32 matmul',
                           'nonlinear':'FP32 erf GELU; FP32 LayerNorm epsilon1e-12; FP32 stable softmax; FP32 pooler tanh',
                           'document_score':'max window positive softmax; strictly greater than frozen threshold'}}
    header=['// Generated byte offsets; stream names and tensor shapes are in manifest.json.', '#pragma once', '#include <cstddef>', 'namespace sentry_parameters {']
    for filename,tensors in streams.items():
        offset=0
        with (out/filename).open('wb') as handle:
            for name,array in tensors:
                handle.write(array.tobytes(order='C'))
                manifest['tensors'].append({'name':name,'file':filename,'offset_bytes':offset,'shape':list(array.shape),'dtype':str(array.dtype),'nbytes':array.nbytes})
                ident=name.replace('.','_')
                header.append(f'constexpr std::size_t {ident} = {offset};')
                offset += array.nbytes
        manifest['files'][filename]={'bytes':offset,'sha256':sha(out/filename)}
    header.append('}')
    (out/'parameters.hpp').write_text('\n'.join(header)+'\n',encoding='utf-8')
    manifest['files']['parameters.hpp']={'bytes':(out/'parameters.hpp').stat().st_size,'sha256':sha(out/'parameters.hpp')}
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    return manifest

def load_export(folder, device='cpu'):
    """Reload exported streams with strict hashes; does not use source weights."""
    from model import ReadableBert
    folder=Path(folder); m=json.loads((folder/'manifest.json').read_text(encoding='utf-8'))
    for name,desc in m['files'].items():
        if sha(folder/name)!=desc['sha256']: raise ValueError('Export stream identity changed: '+name)
    arrays={}
    for t in m['tensors']:
        dtype='<f4' if t['dtype']=='float32' else 'i1'
        with (folder/t['file']).open('rb') as handle:
            handle.seek(t['offset_bytes']); raw=handle.read(t['nbytes'])
        arrays[t['name']]=torch.from_numpy(np.frombuffer(raw,dtype=dtype).copy().reshape(t['shape']))
    state={k:arrays[k] for k in float_keys()}
    scales={}
    for name in LINEARS:
        state[name+'.weight']=arrays[name+'.weight'].float()*arrays[name+'.weight_scale'][:,None]
        scales[name]=float(arrays[name+'.input_scale'][0])
    model=ReadableBert(state,m['model']['config'],m['variant'],scales)
    # Avoid a second quantization / scale estimation in the parameter loader.
    for name in LINEARS:
        getattr(model,name.replace('.','__')+'__codes').copy_(arrays[name+'.weight'])
        getattr(model,name.replace('.','__')+'__scales').copy_(arrays[name+'.weight_scale'])
    return model.to(device),m

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--calibration',required=True,type=Path)
    parser.add_argument('--variant',choices=('w8a8_fp32_attention','w8a8_bf16_attention'),default='w8a8_bf16_attention')
    parser.add_argument('--out',required=True,type=Path)
    args=parser.parse_args(); torch.set_num_threads(1)
    c=json.loads(args.calibration.read_text(encoding='utf-8'))
    if c['data_role']!='fit': raise ValueError('Activation scales must be FIT-only')
    model,meta=load_model(args.variant,c['input_scales'])
    meta.update(calibration_sha256=sha(args.calibration),calibration_identity=c['data_identity'])
    manifest=export_model(model,args.out,meta)
    print(json.dumps({'out':str(args.out),'files':manifest['files'],'manifest_sha256':sha(args.out/'manifest.json')},indent=2))

if __name__=='__main__': main()
